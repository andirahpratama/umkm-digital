const GEMINI_TEXT_MODEL = 'gemini-1.5-flash';
const GEMINI_TEXT_MODEL_ALT = 'gemini-2.0-flash';
const GEMINI_BASE_URL = 'https://generativelanguage.googleapis.com/v1beta/models';

/**
 * Convert File object to base64 data URL
 */
async function fileToBase64(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const result = reader.result;
      const base64 = result.split(',')[1];
      resolve({ base64, mimeType: file.type });
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}

/**
 * Validate Gemini API Key
 */
async function validateGeminiApiKey(apiKey) {
  if (!apiKey || typeof apiKey !== 'string') return false;
  const cleanKey = apiKey.trim();

  if (cleanKey.length < 10) return false;

  try {
    const res = await fetch(
      `${GEMINI_BASE_URL}/${GEMINI_TEXT_MODEL}:generateContent?key=${cleanKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: 'ping' }] }],
          generationConfig: { maxOutputTokens: 5 }
        })
      }
    );

    if (res.ok) return true;

    const errData = await res.json().catch(() => ({}));
    const errMsg = errData?.error?.message || '';

    if (errMsg.toLowerCase().includes('api key not valid') || errMsg.toLowerCase().includes('invalid api key')) {
      return false;
    }

    return cleanKey.length >= 15;
  } catch {
    return cleanKey.length >= 15;
  }
}

/**
 * Pure AI Image Generation Pipeline (Google Flow / Imagen 3 Style)
 */
async function generatePromotionalImage(apiKey, productPhoto, logoFile, theme, promoDesc, platform) {
  const cleanKey = apiKey.trim();

  // 1. Analyze product photo & concept using Gemini Vision
  let visualConcept = {
    foodAnalysis: 'Indonesian F&B product',
    detailedPrompt: 'A brand new commercial advertising poster for delicious food, 8k resolution, food photography, vibrant studio lighting'
  };

  try {
    const aiAnalysis = await analyzePhotoForFullAIPrompt(cleanKey, productPhoto, theme, promoDesc, platform);
    if (aiAnalysis) visualConcept = aiAnalysis;
  } catch (e) {
    console.warn('Vision prompt analysis fallback:', e);
  }

  // 2. Try Imagen 3 API with full prompt generated by Gemini
  try {
    const imagenResult = await tryImagen3FullGen(cleanKey, visualConcept.detailedPrompt, platform);
    if (imagenResult) return imagenResult;
  } catch (err) {
    console.warn('Imagen 3 direct call skipped/failed:', err.message);
  }

  // 3. High-Quality Direct AI Image Generator (Flux Pro Engine - Pure AI 100% Generated Image)
  const isWA = platform === 'wa_story';
  const width = 1080;
  const height = isWA ? 1920 : 1350;
  const seed = Math.floor(Math.random() * 9999999);

  const fluxAiUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(visualConcept.detailedPrompt)}?width=${width}&height=${height}&seed=${seed}&nologo=true&model=flux`;

  try {
    // Fetch generated AI image directly as blob/base64
    const res = await fetch(fluxAiUrl);
    if (res.ok) {
      const blob = await res.blob();
      const base64Data = await new Promise((resolve) => {
        const reader = new FileReader();
        reader.onloadend = () => resolve(reader.result.split(',')[1]);
        reader.readAsDataURL(blob);
      });

      return {
        imageBase64: base64Data,
        mimeType: 'image/jpeg'
      };
    }
  } catch (err) {
    console.error('Flux AI Generation error:', err);
  }

  throw new Error('Gagal memproses AI Image Generation. Coba periksa koneksi atau coba beberapa saat lagi.');
}

/**
 * Gemini Vision Analysis to craft high-detail AI Prompts for Imagen/Flux
 */
async function analyzePhotoForFullAIPrompt(apiKey, productPhoto, theme, promoDesc, platform) {
  const { base64, mimeType } = await fileToBase64(productPhoto);
  const aspect = platform === 'wa_story' ? 'vertical 9:16 aspect ratio' : 'portrait 3:4 aspect ratio';

  const prompt = `You are a world-class F&B Commercial Art Director & AI Prompt Engineer.
Look at this uploaded food/beverage photo.

Create a high-detail English AI image generation prompt to generate a BRAND NEW, 100% fresh, hyper-realistic commercial advertising poster for this food item.

Instructions for prompt:
- Describe the exact food item shown in the photo with mouth-watering details (e.g. crunchy spicy macaroni sprinkled with chili powder, gourmet burger, iced boba milk tea).
- Theme: ${theme || 'Commercial F&B Promotion'}.
- Promo Details: ${promoDesc || 'Special Offer'}.
- Set in a luxurious commercial studio environment (e.g. dark marble table, warm golden spotlights, floating chili/spices particles, elegant promotional typography banner integrated into the image background).
- Style: Professional advertising photography, 8k resolution, cinematic lighting, sharp details, commercial poster design, ${aspect}, no watermarks.

Output ONLY valid JSON without markdown formatting:
{"foodAnalysis": "...", "detailedPrompt": "..."}`;

  const parts = [
    { inlineData: { data: base64, mimeType } },
    { text: prompt }
  ];

  try {
    const res = await fetch(
      `${GEMINI_BASE_URL}/${GEMINI_TEXT_MODEL}:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts }],
          generationConfig: { temperature: 0.8, maxOutputTokens: 500 }
        })
      }
    );

    if (res.ok) {
      const data = await res.json();
      const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
      const cleaned = rawText.replace(/```json|```/g, '').trim();
      return JSON.parse(cleaned);
    }
  } catch (err) {
    console.warn('AI prompt vision analysis error:', err);
  }
  return null;
}

/**
 * Try generating full fresh image via Imagen 3 REST API
 */
async function tryImagen3FullGen(apiKey, detailedPrompt, platform) {
  const res = await fetch(
    `${GEMINI_BASE_URL}/imagen-3.0-generate-002:predict?key=${apiKey}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        instances: [{ prompt: detailedPrompt }],
        parameters: {
          sampleCount: 1,
          aspectRatio: platform === 'wa_story' ? '9:16' : '3:4'
        }
      })
    }
  );

  if (!res.ok) return null;

  const data = await res.json();
  const b64 = data.predictions?.[0]?.bytesBase64Encoded;
  if (b64) {
    return { imageBase64: b64, mimeType: 'image/png' };
  }
  return null;
}

/**
 * Generate viral promotional caption using Gemini Multimodal Vision API
 */
async function generateCaption(apiKey, productPhoto, theme, promoDesc, platform) {
  const cleanKey = apiKey.trim();

  let imagePart = null;
  if (productPhoto && typeof productPhoto === 'object' && productPhoto.name) {
    try {
      const { base64, mimeType } = await fileToBase64(productPhoto);
      imagePart = { inlineData: { data: base64, mimeType } };
    } catch (e) {
      console.warn('Failed to convert product photo for caption:', e);
    }
  }

  const platformConfig = {
    wa_story: `Format: WhatsApp Story (Status WA)
- Maksimal 3-4 kalimat, singkat, menggugah selera makan, dan langsung to the point
- Gunakan emoji yang sangat relevan dan menarik (3-4 emoji)
- Call-To-Action yang mendesak (contoh: "Chat kami sekarang!", "Stok terbatas hari ini!")
- JANGAN gunakan hashtag sama sekali.`,
    instagram: `Format: Instagram Post
- 2-4 baris paragraf dengan Hook kuat di kalimat pertama
- Gunakan line break yang rapi
- Tambahkan 6-8 hashtag F&B dan UMKM populer di bagian akhir
- Call-To-Action jualan (DM / Klik Link di Bio)`
  };

  const promptText = `
Kamu adalah Copywriter Marketing F&B Kelas Dunia & Viral Strategist.
Analisis foto produk makanan/minuman yang diunggah ini.

Tugas: Buat caption promosi yang SANGAT MENARIK, GURIH, dan PERSUASIF untuk produk di foto ini.
Detail Tema: ${theme || 'Promosi Utama Harian'}.
Detail Promo: ${promoDesc || 'Penawaran Spesial Hari Ini'}.

${platformConfig[platform] || platformConfig.wa_story}

ATURAN MUTLAK KUALITAS:
- JANGAN PERNAH menyertakan nama file seperti 'IMG...', 'DCIM...', atau kode angka di dalam caption!
- Kenali jenis makanan di foto (misal: makaroni pedas, nasi goreng, boba, snack, dll) dan buat caption khusus tentang kelezatan makanan tersebut!
- Gunakan Bahasa Indonesia yang natural, kekinian, dan membakar selera makan pembaca.
- HANYA keluarkan teks caption-nya saja, tanpa kata pengantar atau tanda petik.
`.trim();

  const parts = [];
  if (imagePart) parts.push(imagePart);
  parts.push({ text: promptText });

  try {
    const res = await fetch(
      `${GEMINI_BASE_URL}/${GEMINI_TEXT_MODEL}:generateContent?key=${cleanKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts }],
          generationConfig: { temperature: 0.9, maxOutputTokens: 500 }
        })
      }
    );

    if (res.ok) {
      const data = await res.json();
      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (text) return text.trim();
    }

    // Try fallback text model
    const resAlt = await fetch(
      `${GEMINI_BASE_URL}/${GEMINI_TEXT_MODEL_ALT}:generateContent?key=${cleanKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts }],
          generationConfig: { temperature: 0.9, maxOutputTokens: 500 }
        })
      }
    );

    if (resAlt.ok) {
      const dataAlt = await resAlt.json();
      const textAlt = dataAlt.candidates?.[0]?.content?.parts?.[0]?.text;
      if (textAlt) return textAlt.trim();
    }
  } catch (err) {
    console.error('Caption generation error:', err);
  }

  return `🔥 PROMO SPESIAL HARI INI! 😋\nNikmati kelezatan produk F&B pilihan dengan cita rasa gurih & renyah tiada tara. ${promoDesc ? promoDesc + '!' : ''} Pesan sekarang juga sebelum kehabisan! 📱✨`;
}
